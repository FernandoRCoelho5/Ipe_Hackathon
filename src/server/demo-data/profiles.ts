/** Mistura logradouros característicos do bairro com nomes genéricos, de forma estável. */
function streets(primary: readonly string[], offset: number): string[] {
  const generic = GENERIC_STREETS.map(
    (_, i) => GENERIC_STREETS[(i + offset) % GENERIC_STREETS.length],
  );
  return [...primary, ...generic.slice(0, Math.max(0, 7 - primary.length))];
}

