import type { DailyWeather } from "@/domain/thermal/diurnal";
import type { LngLat } from "@/domain/shared/geo";

/**
 * Perfis que guiam a geração dos dados DEMONSTRATIVOS.
 * Nomes de bairros são reais; posições, malha de quarteirões, logradouros secundários
 * e indicadores são SINTÉTICOS e aproximados (ver docs/DATA.md).
 */

export type NeighborhoodKind =
  "centro" | "misto" | "residencial-medio" | "residencial-alto" | "periferia" | "industrial";

export interface NeighborhoodProfile {
  name: string;
  kind: NeighborhoodKind;
  /** Deslocamento do centro do bairro em relação ao centro do município (km leste, km norte). */
  offsetKm: readonly [east: number, north: number];
  radiusKm: number;
  /** Propensão ao calor (0–1): materiais, adensamento, atividade industrial. */
  heat: number;
  canopy: number;
  incomePerCapita: number;
  elderlyShare: number;
  densityPerKm2: number;
  /** Multiplicador de circulação de pedestres. */
  pedestrian: number;
  streets: readonly string[];
}

export interface MunicipalityProfile {
  municipalityId: string;
  codePrefix: string;
  center: LngLat;
  /** Traçado aproximado do Rio Paraíba do Sul na área urbana. */
  river: readonly LngLat[];
  weather: DailyWeather;
  neighborhoods: readonly NeighborhoodProfile[];
}

